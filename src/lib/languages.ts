// A backend message key (LANG_...) in the user's language, or a generic error.
export function translateMessage(translations: Translations, key?: string): string {
    return (key && translations[key]) || translations.LANG_ERROR_GENERIC
}

export function getTranslations(language: string): Translations {
    return languages[language] || languages['en']
}

export function resolveLanguage(): string {
    return navigator.language.toLowerCase().startsWith('ro') ? 'ro' : 'en'
}

export default languages
